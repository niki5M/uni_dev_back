#!/bin/bash
# Скрипт для быстрой установки зависимостей
# Использует pip с флагом --only-binary для избежания компиляции

echo "Установка зависимостей (только бинарные пакеты)..."
pip install --only-binary :all: -r requirements.txt

# Если не получилось, пробуем обычную установку
if [ $? -ne 0 ]; then
    echo "Бинарные пакеты не найдены, устанавливаем обычным способом..."
    pip install -r requirements.txt
fi

echo "Установка завершена!"



